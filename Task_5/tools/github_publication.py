#!/usr/bin/env python3
"""Check/export only explicitly selected Task 5 research and application files."""
import argparse
import ast
import hashlib
import json
from pathlib import Path, PurePosixPath
import re
import shutil

ROOT = Path(__file__).resolve().parent.parent
MANIFEST = ROOT / 'publication_files.json'
FORBIDDEN_PARTS = {'certificates', 'packages', 'sessions', 'deleted_sessions', 'Recordings',
                   'owner_credentials', 'data', 'dev_data', 'sources', 'assets', '.runtime',
                   '__pycache__', '.uploads', 'author_case_sources'}
FORBIDDEN_NAMES = {'sample_case.json', 'collection_selection.json', 'campus_owner.json',
                   'config.production.json', 'accounts.sqlite3', 'browser_fixture_test.go'}
EXTENSIONS = {'.py', '.sh', '.md', '.json', '.csv', '.html', '.css', '.js', '.go', '.mod'}
PATTERNS = [
    ('private key', re.compile(r'-----BEGIN (?:[A-Z0-9]+ )*PRIVATE KEY-----')),
    # A legacy browser test contains a 1x1 synthetic PNG (96 base64 chars).
    ('embedded image payload', re.compile(r'data:image/[^;\s]+;base64,[A-Za-z0-9+/]{512}')),
    ('GitHub token', re.compile(r'\b(?:gh[pousr]_[A-Za-z0-9]{30,}|github_pat_[A-Za-z0-9_]{40,})')),
    ('Hugging Face token', re.compile(r'\bhf_[A-Za-z0-9]{30,}')),
    ('deployment password', re.compile(r'\b[A-Za-z0-9_-]+_(?:admin|ugp_ts_' + r'pil)@\d{4}\b')),
    ('credential in URL', re.compile(r'https?://[^\s/@:]+:[^\s/@]+@')),
]


def selected_files():
    data = json.loads(MANIFEST.read_text())
    names = data['files']
    if names != sorted(set(names)):
        raise ValueError('Manifest files must be sorted and unique.')
    for name in names:
        path = PurePosixPath(name)
        if path.is_absolute() or '..' in path.parts or str(path) != name:
            raise ValueError('Invalid publication path: ' + name)
        if set(path.parts) & FORBIDDEN_PARTS or path.name in FORBIDDEN_NAMES:
            raise ValueError('Private/generated publication path: ' + name)
        if path.name.startswith('verify_') and path.suffix == '.py':
            raise ValueError('Generated verification scripts stay local: ' + name)
        if path.suffix not in EXTENSIONS and name not in {'.gitignore', 'Route_length_Instructions'}:
            raise ValueError('Unexpected publication type: ' + name)
        source = ROOT / name
        if any(parent.is_symlink() for parent in [source, *source.parents] if parent != ROOT.parent):
            raise ValueError('Linked publication input: ' + name)
        if not source.is_file() or not source.resolve().is_relative_to(ROOT):
            raise ValueError('Missing/outside publication input: ' + name)
    return names


def ignore_rules(names):
    directories = {str(parent) for name in names for parent in PurePosixPath(name).parents
                   if str(parent) != '.'}
    lines = ['# Generated by tools/github_publication.py --write-ignore.',
             '# Everything stays local unless listed in publication_files.json.', '*']
    lines += ['!/' + name + '/' for name in sorted(directories, key=lambda name: (name.count('/'), name))]
    lines += ['!/' + name for name in names]
    return '\n'.join(lines) + '\n'


def validate(names):
    inventory = []
    for name in names:
        source = ROOT / name
        payload = source.read_bytes()
        if len(payload) > 1024 * 1024:
            raise ValueError('Publication file exceeds 1 MiB: ' + name)
        value = payload.decode('utf-8')
        for label, pattern in PATTERNS:
            if pattern.search(value):
                # Report the filename, never the matched credential/payload.
                raise ValueError(label + ' detected in ' + name)
        if source.suffix == '.py':
            ast.parse(value, filename=name)
        if source.suffix == '.json':
            json.loads(value)
        inventory.append({'path': name, 'bytes': len(payload), 'sha256': hashlib.sha256(payload).hexdigest()})
    if (ROOT / '.gitignore').read_text() != ignore_rules(names):
        raise ValueError('Ignore rules differ from manifest; run --write-ignore.')
    return inventory


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='Check manifest, source syntax and payload guards.')
    parser.add_argument('--write-ignore', action='store_true', help='Regenerate Task 5 ignore rules from the manifest.')
    parser.add_argument('--export', type=Path, help='Copy only the selected files into a new directory.')
    parser.add_argument('--inventory', type=Path, help='Write file hashes/sizes to an optional local report.')
    args = parser.parse_args()
    names = selected_files()
    if args.write_ignore:
        (ROOT / '.gitignore').write_text(ignore_rules(names))
    inventory = validate(names)
    if args.export:
        destination = args.export.absolute()
        if destination.exists():
            raise ValueError('Export destination must be new: ' + str(destination))
        if destination.is_relative_to(ROOT):
            raise ValueError('Export outside Task 5 to avoid recursive copies.')
        destination.mkdir(parents=True)
        for name in names:
            target = destination / name
            target.parent.mkdir(parents=True, exist_ok=True)
            shutil.copy2(ROOT / name, target)
        print('Exported source to', destination)
    if args.inventory:
        args.inventory.write_text(json.dumps(inventory, indent=2) + '\n')
    print(f'Checked {len(names)} selected files ({sum(row["bytes"] for row in inventory):,} bytes).')


if __name__ == '__main__':
    main()
