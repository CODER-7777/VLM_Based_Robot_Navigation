"""List repository files and source paths without reading assets or private state."""
import csv
from collections import Counter, defaultdict
from datetime import datetime, timezone
import json
import os
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
TASK = ROOT/'Task_2'
SKIP = {'.git', '.agents', '.aws', '.codex', '.venv', 'venv', 'env', 'envs',
        'node_modules', '__pycache__', '.cache', '.pytest_cache', '.mypy_cache',
        'browser_profile', 'browser-profile', 'chrome-profile', 'chromium-profile',
        '.ruff_cache'}
OUTPUTS = {'Task_2/repository_inventory.csv', 'Task_2/repository_inventory_summary.json',
           'Task_2/REPOSITORY_FILE_INDEX.md'}
SOURCE = {'.py', '.sh', '.bash', '.js', '.ts', '.tsx', '.jsx', '.html', '.css',
          '.c', '.cpp', '.h', '.hpp', '.cu', '.toml', '.yaml', '.yml', '.xml', '.urdf'}
rows, skipped = [], []
for directory, names, files in os.walk(ROOT, followlinks=False):
    parent = Path(directory)
    excluded = [n for n in names if n in SKIP or n.startswith('.venv') or 'browser_profile' in n]
    skipped.extend(str((parent/n).relative_to(ROOT)) for n in excluded)
    names[:] = sorted(n for n in names if n not in excluded and not (parent/n).is_symlink())
    for name in sorted(files):
        path = parent/name
        relative = str(path.relative_to(ROOT))
        if relative in OUTPUTS or name == '.git' or path.is_symlink():
            continue
        try:
            size = path.stat().st_size
        except OSError:
            continue
        kind = 'source/config' if path.suffix in SOURCE else 'documentation' if path.suffix == '.md' else 'artifact/data'
        rows.append({'path':relative, 'bytes':size, 'kind':kind})
rows.sort(key=lambda r:r['path'])
with (TASK/'repository_inventory.csv').open('w', newline='') as f:
    writer = csv.DictWriter(f, fieldnames=['path','bytes','kind'])
    writer.writeheader()
    writer.writerows(rows)
areas = defaultdict(lambda: {'files':0, 'bytes':0, 'source_config_files':0, 'documentation_files':0})
groups = defaultdict(list)
for r in rows:
    parts = Path(r['path']).parts
    area = parts[0] if len(parts)>1 else '(root files)'
    areas[area]['files'] += 1
    areas[area]['bytes'] += r['bytes']
    if r['kind'] == 'source/config':
        areas[area]['source_config_files'] += 1
    if r['kind'] == 'documentation':
        areas[area]['documentation_files'] += 1
    if r['kind'] != 'artifact/data':
        group = '/'.join(parts[:2]) if len(parts)>2 else area
        groups[group].append(r)
summary = {'created_utc':datetime.now(timezone.utc).isoformat(), 'root':str(ROOT),
           'scope':'Filesystem inventory; presence is not code review, successful execution, or Git publication.',
           'files':len(rows), 'bytes':sum(r['bytes'] for r in rows), 'areas':dict(sorted(areas.items())),
           'excluded_directory_names':sorted(SKIP), 'excluded_paths':sorted(skipped),
           'symlinks_followed':False, 'binary_contents_read':False}
(TASK/'repository_inventory_summary.json').write_text(json.dumps(summary, indent=2)+'\n')
lines = ['# Repository source and documentation index', '',
         'Generated by `build_repository_index.py`. All indexed source/configuration and Markdown paths are listed below. '
         'Every other included file is listed with its byte size in [repository_inventory.csv](repository_inventory.csv). '
         'Private state, Git internals, environments, caches and browser profiles are excluded; links are not followed. '
         'This is a path inventory, not a claim that every file has been executed or reviewed.', '',
         '| Area | Files | Source/config | Markdown | Bytes |', '| --- | ---: | ---: | ---: | ---: |']
for area, count in sorted(areas.items()):
    lines.append(f"| {area} | {count['files']} | {count['source_config_files']} | {count['documentation_files']} | {count['bytes']} |")
for group, members in sorted(groups.items()):
    lines.extend(['', f'## {group}', ''])
    for r in members:
        # Links are relative to Task_2, including nested-repository sources.
        label = r['path']
        target = '../'+r['path']
        lines.append(f"- [{label}](<{target}>) — {r['bytes']} bytes")
(TASK/'REPOSITORY_FILE_INDEX.md').write_text('\n'.join(lines)+'\n')
print(json.dumps({'files':summary['files'], 'areas':summary['areas']}, indent=2))
